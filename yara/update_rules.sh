#!/usr/bin/env bash
# Pull the latest YARA rules from upstream signature repositories and assemble
# a single compiled index that Wazuh agents / Suricata file-extraction scanning
# can use.
#
# Sources:
#   - Neo23x0/signature-base   (Florian Roth, broad malware coverage)
#   - Yara-Rules/rules         (community ruleset)
#
# Output: yara/compiled/sybsec-index.yar  (an index that includes all valid rules)
#         yara/compiled/sybsec.yarc        (compiled, if `yarac` is available)
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC_DIR="${ROOT}/sources"
OUT_DIR="${ROOT}/compiled"
INDEX="${OUT_DIR}/sybsec-index.yar"

declare -A REPOS=(
  [signature-base]="https://github.com/Neo23x0/signature-base.git"
  [yara-rules]="https://github.com/Yara-Rules/rules.git"
)

mkdir -p "${SRC_DIR}" "${OUT_DIR}"
command -v git >/dev/null || { echo "git required" >&2; exit 1; }

# 1. Clone/update each source repo (shallow).
for name in "${!REPOS[@]}"; do
  dest="${SRC_DIR}/${name}"
  if [ -d "${dest}/.git" ]; then
    echo ">> updating ${name}"
    git -C "${dest}" pull --ff-only --quiet || echo "  ! pull failed for ${name}"
  else
    echo ">> cloning ${name}"
    git clone --depth 1 "${REPOS[$name]}" "${dest}"
  fi
done

# 2. Build an index that `include`s every .yar/.yara file. Skip known-broken or
#    rules requiring external modules not present (cuckoo, etc.) to keep the
#    index loadable.
echo ">> building index ${INDEX}"
: > "${INDEX}"
{
  echo "// sybsec YARA index - generated by yara/update_rules.sh"
  echo "// $(find "${SRC_DIR}" -name '*.yar' -o -name '*.yara' | wc -l) candidate files"
} >> "${INDEX}"

added=0
while IFS= read -r f; do
  # Skip rules that import modules we cannot guarantee at scan time.
  if grep -qE '^\s*import\s+"(cuckoo|androguard|dotnet)"' "$f"; then
    continue
  fi
  rel="${f#"${ROOT}/"}"
  echo "include \"../${rel}\"" >> "${INDEX}"
  added=$((added + 1))
done < <(find "${SRC_DIR}" \( -name '*.yar' -o -name '*.yara' \) | sort)

echo ">> indexed ${added} rule files"

# 3. Optionally compile for faster scanning + early validation.
if command -v yarac >/dev/null 2>&1; then
  echo ">> compiling with yarac"
  if yarac "${INDEX}" "${OUT_DIR}/sybsec.yarc" 2>"${OUT_DIR}/compile.log"; then
    echo ">> compiled -> ${OUT_DIR}/sybsec.yarc"
  else
    echo "  ! some rules failed to compile; see ${OUT_DIR}/compile.log"
  fi
else
  echo ">> yarac not installed; skipping compile (index still usable)"
fi

echo ">> deploy: push ${OUT_DIR}/ to agents via wazuh/active-response/push-yara-rule.sh"
